#!/usr/bin/env python3
"""Generates assets/bg_<theme>.png, the 960x544 background of every menu, one
per colour theme (src/gui/theme.c lists the themes and their colours).

The picture is drawn from scratch (no third-party artwork): a lunar sky. A
vertical gradient, a few faint stars (none behind the top bar's text, fewer
towards the horizon), a large faint crescent low on the right whose disc is the
one of the logo seen from closer, and a soft glow on the horizon. Each theme has
one touch of its own: aurora curtains, a warm dawn horizon, and for Eclipse a
dark disc with a thin corona. Everything is kept faint so that text drawn on top
stays readable, and the picture is dithered so that it shows no banding on the
Vita screen. The app draws it as one texture per frame, like any picture.

    python3 tools/make_background.py [output folder]
    python3 tools/make_background.py --stars src/gui/stars.h   (where the stars are)

Each theme also gets bg_<theme>_sky.png, the same sky without its stars, for
the animated background (the app draws turning stars over it).

Needs numpy and Pillow.
"""
import sys

import numpy as np
from PIL import Image

W, H = 960, 544

THEMES = {
    "night": ([(0, (4, 20, 48)), (120, (8, 45, 94)), (330, (14, 66, 128)), (544, (16, 56, 102))],
              (0.55, 0.85, 1.0)),
    "dawn": ([(0, (30, 9, 6)), (120, (70, 26, 15)), (330, (118, 50, 30)), (544, (96, 40, 25))],
             (1.0, 0.75, 0.55)),
    "aurora": ([(0, (2, 18, 20)), (120, (4, 42, 44)), (330, (8, 70, 66)), (544, (7, 56, 54))],
               (0.55, 1.0, 0.85)),
    "twilight": ([(0, (16, 6, 32)), (120, (38, 15, 72)), (330, (66, 30, 114)), (544, (52, 24, 90))],
                 (0.82, 0.62, 1.0)),
    "eclipse": ([(0, (7, 7, 9)), (120, (16, 16, 19)), (330, (30, 30, 35)), (544, (24, 24, 28))],
                (1.0, 0.82, 0.5)),
}

# Per theme: how many stars, how bright the moon disc is, horizon glow strength.
STYLE = {
    "night": dict(stars=60, moon=11.0, horizon=10.0),
    "dawn": dict(stars=25, moon=9.0, horizon=26.0),
    "aurora": dict(stars=50, moon=8.0, horizon=8.0),
    "twilight": dict(stars=80, moon=10.0, horizon=14.0),
    "eclipse": dict(stars=70, moon=0.0, horizon=4.0),
}

BAYER = np.array([
    [0, 32, 8, 40, 2, 34, 10, 42],
    [48, 16, 56, 24, 50, 18, 58, 26],
    [12, 44, 4, 36, 14, 46, 6, 38],
    [60, 28, 52, 20, 62, 30, 54, 22],
    [3, 35, 11, 43, 1, 33, 9, 41],
    [51, 19, 59, 27, 49, 17, 57, 25],
    [15, 47, 7, 39, 13, 45, 5, 37],
    [63, 31, 55, 23, 61, 29, 53, 21],
]) / 64.0

MOON_C = (858.0, 610.0)   # centre of the big moon, below the bottom-right corner
MOON_R = 300.0


def star_list(name):
    """The stars of a theme's picture: (x, y, size, brightness), always the same."""
    st = STYLE[name]
    rng = np.random.default_rng({"night": 7, "dawn": 11, "aurora": 3, "twilight": 5, "eclipse": 9}[name])
    stars = []
    while len(stars) < st["stars"]:
        x, y = rng.uniform(0, W), rng.uniform(0, H)
        if rng.uniform() > (1.0 - y / H) ** 1.4:
            continue
        if np.hypot(x - MOON_C[0], y - MOON_C[1]) < MOON_R + 20:
            continue
        # Keep the top bar's text clear (name on the left, status on the right).
        if y < 58 and (x < 280 or x > 690):
            continue
        size = rng.choice([0.55, 0.7, 0.9, 1.2], p=[0.45, 0.3, 0.17, 0.08])
        bright = rng.uniform(45, 115) * (1.0 - 0.6 * y / H)
        stars.append((x, y, size, bright))
    return stars


def write_stars_header(path):
    """src/gui/stars.h: where the stars of each picture are, for the app to make
    them twinkle (theme.c). Pixel centres are at +0.5, as drawn above."""
    lines = ["/* Generated by tools/make_background.py --stars: the stars drawn in",
             " * assets/bg_<theme>.png (x, y in pixels, size and brightness as drawn),",
             " * so that theme.c can make them twinkle. Do not edit. */",
             "#ifndef STARS_H", "#define STARS_H", "",
             "typedef struct { float x, y, size, bright; } bg_star;", ""]
    names = list(THEMES)
    for name in names:
        stars = star_list(name)
        lines.append("static const bg_star k_stars_%s[%d] = {" % (name, len(stars)))
        for x, y, size, bright in stars:
            lines.append("  {%.2ff, %.2ff, %.2ff, %.1ff}," % (x, y, size, bright))
        lines.append("};")
    lines.append("")
    lines.append("/* Moving sky: stars turning around the big moon, centre (%.0f, %.0f): offset" % MOON_C)
    lines.append(" * from it in pixels, size and brightness as drawn (before the horizon), and")
    lines.append(" * depth: the star shows where (1 - y/H)^1.4 is above it (orbit.h). */")
    lines.append("#define ORBIT_CX %.1ff" % MOON_C[0])
    lines.append("#define ORBIT_CY %.1ff" % MOON_C[1])
    lines.append("typedef struct { float dx, dy, size, bright, depth; } orbit_star;")
    for name in names:
        stars = orbit_star_list(name)
        lines.append("static const orbit_star k_orbit_%s[%d] = {" % (name, len(stars)))
        for dx, dy, size, bright, depth in stars:
            lines.append("  {%.2ff, %.2ff, %.2ff, %.1ff, %.4ff}," % (dx, dy, size, bright, depth))
        lines.append("};")
    lines.append("")
    lines.append("/* In the order of the THEME_* values (src/gui/theme.h). */")
    lines.append("static const bg_star *const k_theme_stars[] = {%s};" % ", ".join("k_stars_" + n for n in names))
    lines.append("static const int k_theme_star_count[] = {%s};" %
                 ", ".join("(int)(sizeof(k_stars_%s) / sizeof(k_stars_%s[0]))" % (n, n) for n in names))
    lines.append("static const orbit_star *const k_theme_orbit[] = {%s};" % ", ".join("k_orbit_" + n for n in names))
    lines.append("static const int k_theme_orbit_count[] = {%s};" %
                 ", ".join("(int)(sizeof(k_orbit_%s) / sizeof(k_orbit_%s[0]))" % (n, n) for n in names))
    lines.append("")
    lines.append("#endif // STARS_H")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("written:", path)


# Moving sky (Settings > General): the stars turn slowly around the big moon.
# The picture is then drawn without its stars (bg_<theme>_sky.png) and the app
# draws these instead (theme.c, orbit.h). They fill the whole ring the screen
# can see while it turns, as evenly as the still stars at the top of the
# picture; the horizon is applied by the app where each star is at the time
# (fewer and dimmer towards the bottom, as in star_list()), so that the sky
# looks the same at every moment as the still picture.
ORBIT_R_MIN = MOON_R + 20.0
ORBIT_R_MAX = float(np.hypot(MOON_C[0], MOON_C[1])) + 8.0   # the far corner of the screen
GOLDEN = (np.sqrt(5.0) - 1.0) / 2.0


def still_share():
    """The screen's area as star_list() fills it: each pixel weighted by the
    share of stars kept at its height, without the moon and the top bar's text,
    where no star goes (their stars land elsewhere)."""
    gy, gx = np.mgrid[0:H, 0:W] + 0.5
    keep = (1.0 - gy / H) ** 1.4
    keep[np.hypot(gx - MOON_C[0], gy - MOON_C[1]) < MOON_R + 20] = 0.0
    keep[(gy < 58) & ((gx < 280) | (gx > 690))] = 0.0
    return float(keep.sum())


def orbit_star_list(name):
    """Stars around the moon: (dx, dy from its centre, size, brightness, depth),
    always the same. depth (0..1) is how high on the screen the star must be to
    show: it shows where (1 - y/H)^1.4 is above it, which keeps the same share
    of stars at each height as star_list().

    The ring is cut into cells of equal area, one star in each, and the depths
    follow the golden ratio along each band: any part of the sky that comes
    into view then holds about as many stars as the still picture, and they
    still look scattered."""
    st = STYLE[name]
    rng = np.random.default_rng({"night": 107, "dawn": 111, "aurora": 103, "twilight": 105, "eclipse": 109}[name])
    density = st["stars"] / still_share()   # stars per pixel where all are kept (the top)
    count = density * np.pi * (ORBIT_R_MAX ** 2 - ORBIT_R_MIN ** 2)
    bands = max(4, int(round(np.sqrt(count / 4.0))))
    sectors = int(round(count / bands))
    step = (ORBIT_R_MAX ** 2 - ORBIT_R_MIN ** 2) / bands
    stars = []
    for b in range(bands):
        turn = rng.uniform()   # each band starts elsewhere: no spokes
        first = rng.uniform()
        for j in range(sectors):
            r = np.sqrt(ORBIT_R_MIN ** 2 + step * (b + rng.uniform()))   # even over the cell's area
            a = 2.0 * np.pi * ((j + rng.uniform() + turn) / sectors)
            size = rng.choice([0.55, 0.7, 0.9, 1.2], p=[0.45, 0.3, 0.17, 0.08])
            bright = rng.uniform(45, 115)
            depth = (first + j * GOLDEN + rng.uniform(-0.03, 0.03)) % 1.0
            stars.append((r * np.cos(a), r * np.sin(a), size, bright, depth))
    return stars


def draw(name, stops, tint, out, with_stars=True):
    st = STYLE[name]
    rows = np.arange(H, dtype=np.float64)
    cols = np.arange(W, dtype=np.float64)
    yy, xx = np.meshgrid(rows, cols, indexing="ij")

    img = np.zeros((H, W, 3))
    stop_rows = [s[0] for s in stops]
    for c in range(3):
        img[:, :, c] = np.interp(rows, stop_rows, [s[1][c] for s in stops])[:, None]

    light = np.zeros((H, W))

    # Horizon: a soft glow rising from the bottom edge.
    light += st["horizon"] * np.exp(-(H - 1 - yy) / 70.0)

    # The big moon: a faint disc with a brighter limb and a soft halo.
    d = np.hypot(xx - MOON_C[0], yy - MOON_C[1])
    if name == "eclipse":
        # Dark disc, thin bright corona around it.
        light += 34.0 * np.exp(-((d - MOON_R) ** 2) / (2 * 2.2 ** 2))
        light += 16.0 * np.exp(-np.maximum(d - MOON_R, 0) / 26.0) * (d >= MOON_R)
        img *= np.where(d < MOON_R, 0.55, 1.0)[:, :, None]
    else:
        inside = d < MOON_R
        # Lit crescent: the part of the disc not covered by a second disc shifted down-right.
        d2 = np.hypot(xx - (MOON_C[0] + 70.0), yy - (MOON_C[1] + 40.0))
        lit = inside & (d2 > MOON_R * 0.98)
        light += st["moon"] * inside
        light += st["moon"] * 1.6 * lit
        light += 7.0 * np.exp(-((d - MOON_R) ** 2) / (2 * 1.2 ** 2)) * (d2 > MOON_R)
        light += 9.0 * np.exp(-np.maximum(d - MOON_R, 0) / 40.0) * (d >= MOON_R)

    # Aurora curtains: soft vertical bands in the upper half.
    if name == "aurora":
        band = (np.sin(xx / 61.0 + 0.8) * 0.5 + 0.5) * (np.sin(xx / 23.0 + 2.1) * 0.3 + 0.7)
        curtain = np.exp(-((yy - (120 + 40 * np.sin(xx / 140.0))) ** 2) / (2 * 55.0 ** 2))
        light += 26.0 * band * curtain

    img += light[:, :, None] * np.array(tint)[None, None, :]

    # Stars: few, small, faint; fewer towards the horizon.
    star = np.zeros((H, W))
    for x, y, size, bright in (star_list(name) if with_stars else []):
        x0, x1 = int(max(x - 4, 0)), int(min(x + 5, W))
        y0, y1 = int(max(y - 4, 0)), int(min(y + 5, H))
        gy, gx = np.meshgrid(np.arange(y0, y1), np.arange(x0, x1), indexing="ij")
        star[y0:y1, x0:x1] += bright * np.exp(-((gx + 0.5 - x) ** 2 + (gy + 0.5 - y) ** 2) / (2 * size ** 2))
    white = np.array([0.92, 0.95, 1.0])
    img += np.minimum(star, 200)[:, :, None] * white[None, None, :]

    tile = np.tile(BAYER, (H // 8 + 1, W // 8 + 1))[:H, :W]
    img = np.floor(img + tile[:, :, None])
    Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), "RGB").save(out, optimize=True)
    print("written:", out)


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "--stars":
        write_stars_header(sys.argv[2])
        return
    folder = sys.argv[1] if len(sys.argv) > 1 else "assets"
    for name, (stops, tint) in THEMES.items():
        draw(name, stops, tint, "%s/bg_%s.png" % (folder, name))
        draw(name, stops, tint, "%s/bg_%s_sky.png" % (folder, name), with_stars=False)


if __name__ == "__main__":
    main()
