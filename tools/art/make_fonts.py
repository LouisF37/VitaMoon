#!/usr/bin/env python3
"""Builds the interface fonts in assets/ and the table of the characters the
title font has (src/gui/title_font_cover.h).

    python3 tools/art/make_fonts.py [Inter folder] [Poppins-Regular.ttf]

- assets/Inter-Regular.otf and assets/Inter-Light.otf: the interface text.
- assets/Poppins-Regular.ttf: titles (the logo's typeface, in its Bold).

All three are cut down to the characters VitaMoon can meet: Latin for
Western, Central and Eastern European languages and Vietnamese, Greek,
Cyrillic, punctuation, currency signs, arrows (what Roboto, the previous
interface font, had for these scripts). Inter has all of them;
Poppins has the Latin part only, and not all of it, so the titles fall back to
Inter Light for any text with a character missing from Poppins (theme.c reads
the table written here). Both fonts are under the SIL Open Font License 1.1
and declare no Reserved Font Name, so the cut-down files keep their names
(assets/LICENSE.Inter, assets/LICENSE.Poppins).

Defaults: Debian's fonts-inter package and the Google Fonts copy of Poppins.
Needs fontTools.
"""
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
INTER_DIR = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/opentype/inter'
POPPINS = sys.argv[2] if len(sys.argv) > 2 else '/usr/share/fonts/truetype/google-fonts/Poppins-Regular.ttf'

RANGES = [
    (0x0020, 0x007E),  # Basic Latin
    (0x00A0, 0x017F),  # Latin-1 and Latin Extended-A
    (0x0192, 0x0192),  # florin
    (0x01A0, 0x01B0),  # Vietnamese horned O and U
    (0x0218, 0x021B),  # Romanian S and T with comma below
    (0x02C6, 0x02DD),  # spacing accents
    (0x0300, 0x0323),  # combining accents
    (0x0370, 0x03FF),  # Greek
    (0x0400, 0x052F),  # Cyrillic and its supplement
    (0x1E80, 0x1E85),  # Welsh W with accents
    (0x1EA0, 0x1EF9),  # Vietnamese
    (0x2000, 0x206F),  # general punctuation
    (0x20A0, 0x20CF),  # currency signs
    (0x2116, 0x2116),  # numero sign
    (0x2122, 0x2122),  # trade mark
    (0x2190, 0x2199),  # arrows
]


def unicodes():
    out = []
    for lo, hi in RANGES:
        out.extend(range(lo, hi + 1))
    return out


def cut(src, dst):
    opts = subset.Options()
    opts.layout_features = ['kern']
    opts.name_IDs = ['*']        # keep the copyright and licence records
    opts.name_languages = ['*']
    opts.notdef_outline = True
    font = TTFont(src)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=unicodes())
    sub.subset(font)
    font.save(dst)
    print('written: %s (%d bytes)' % (os.path.relpath(dst, ROOT), os.path.getsize(dst)))
    return font


def runs(cps):
    out = []
    for c in sorted(cps):
        if out and c == out[-1][1] + 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def main():
    cut(os.path.join(INTER_DIR, 'Inter-Regular.otf'), os.path.join(ROOT, 'assets', 'Inter-Regular.otf'))
    cut(os.path.join(INTER_DIR, 'Inter-Light.otf'), os.path.join(ROOT, 'assets', 'Inter-Light.otf'))
    poppins = cut(POPPINS, os.path.join(ROOT, 'assets', 'Poppins-Regular.ttf'))

    covered = set(poppins.getBestCmap()) & set(unicodes())
    table = runs(covered)
    lines = ['/* Generated by tools/art/make_fonts.py: the characters the title font',
             ' * (assets/Poppins-Regular.ttf) has, as ranges of code points. A title',
             ' * with any other character is drawn with Inter Light (theme.c). */',
             '#ifndef TITLE_FONT_COVER_H',
             '#define TITLE_FONT_COVER_H',
             '',
             'static const unsigned int k_title_cover[][2] = {']
    for lo, hi in table:
        lines.append('  {0x%04X, 0x%04X},' % (lo, hi))
    lines += ['};', '#define TITLE_COVER_COUNT ((int)(sizeof(k_title_cover) / sizeof(k_title_cover[0])))',
              '', '#endif // TITLE_FONT_COVER_H', '']
    path = os.path.join(ROOT, 'src', 'gui', 'title_font_cover.h')
    with open(path, 'w') as f:
        f.write('\n'.join(lines))
    print('written: %s (%d ranges, %d characters)' % (os.path.relpath(path, ROOT), len(table), len(covered)))


if __name__ == '__main__':
    main()
